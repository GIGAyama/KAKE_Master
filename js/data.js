export const STAGES = [1, 2, 3, 4, 5, 6, 7, 8, 9];

// カードオブジェクトを生成
export function makeCard(a, b) {
  return { a, b, ans: a * b, yomi: YOMI[a][b - 1], key: `${a}-${b}` };
}

// 選択された段からデッキを生成(order: 'asc' | 'desc' | 'random')
export function buildDeck(stages, order) {
  const list = [];
  [...stages].sort((x, y) => x - y).forEach((a) => {
    for (let b = 1; b <= 9; b++) list.push(makeCard(a, b));
  });
  if (order === 'desc') list.reverse();
  if (order === 'random') shuffle(list);
  return list;
}

// Fisher-Yates シャッフル
export function shuffle(list) {
  for (let i = list.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [list[i], list[j]] = [list[j], list[i]];
  }
  return list;
}
